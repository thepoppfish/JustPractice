export type AchievementIconCategory =
  | 'library'
  | 'completed'
  | 'watch'
  | 'streak'
  | 'level'
  | 'meta';

export function icoAchievement(category: AchievementIconCategory | string): string {
  switch (category) {
    case 'library':
      return icoBook();
    case 'completed':
      return icoCheck();
    case 'watch':
      return icoClock();
    case 'streak':
      return icoFlame();
    case 'level':
      return icoStar();
    case 'meta':
      return icoMedal();
    default:
      return icoTrophy();
  }
}
