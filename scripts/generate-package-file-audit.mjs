/**
 * Generate docs/PACKAGE-FILE-AUDIT.csv and docs/PACKAGE-FILE-AUDIT.md
 * Rates each path: required=1 (must ship in store zip) or required=0 (dev-only).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { collectDistClosure, distDir, norm, root } from './package-dist-closure.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const docsDir = path.join(root, 'docs');

const SKIP_DIRS = new Set(['node_modules', '.git']);

const BUILD_SCRIPTS = new Set([
  'scripts/build-youtube-bundle.mjs',
  'scripts/generate-icons.mjs',
  'scripts/patch-crx-build.mjs',
  'scripts/vite-plugin-youtube-bundle.ts',
  'scripts/verify-extension-dist.mjs',
]);

/** @type {Map<string, { required: 0|1, category: string, notes: string }>} */
const entries = new Map();

function addEntry(relPath, required, category, notes = '') {
  const key = norm(relPath);
  if (!entries.has(key)) {
    entries.set(key, { required, category, notes });
  }
}

function walkDir(absDir, relPrefix, onFile) {
  if (!fs.existsSync(absDir)) return;
  for (const name of fs.readdirSync(absDir)) {
    if (SKIP_DIRS.has(name)) continue;
    const abs = path.join(absDir, name);
    const rel = relPrefix ? `${relPrefix}/${name}` : name;
    const st = fs.statSync(abs);
    if (st.isDirectory()) {
      walkDir(abs, rel, onFile);
    } else if (st.isFile()) {
      onFile(norm(rel), abs);
    }
  }
}

function categorizeRepoFile(rel) {
  if (rel.startsWith('dist/')) return null;

  if (rel.startsWith('src/')) {
    if (rel.endsWith('.test.ts')) {
      return { required: 0, category: 'test', notes: 'unit test; compiled away' };
    }
    return { required: 0, category: 'source', notes: 'TypeScript source; bundled into dist' };
  }

  if (rel.startsWith('public/')) {
    return { required: 0, category: 'public-input', notes: 'static build input; not shipped as-is' };
  }

  if (rel.startsWith('docs/')) {
    return { required: 0, category: 'docs', notes: 'documentation' };
  }

  if (rel.startsWith('assets/logo-intro/')) {
    return { required: 0, category: 'asset-dev', notes: 'logo intro video render pipeline' };
  }

  if (rel.startsWith('scripts/')) {
    const note = BUILD_SCRIPTS.has(rel) ? 'build pipeline input' : 'dev tooling';
    return { required: 0, category: 'script', notes: note };
  }

  if (
    rel === 'vite.config.ts' ||
    rel === 'manifest.config.ts' ||
    rel === 'vitest.config.ts' ||
    rel === 'eslint.config.js' ||
    rel.startsWith('tsconfig')
  ) {
    return { required: 0, category: 'config', notes: 'build/dev config' };
  }

  if (rel.endsWith('.md')) {
    return { required: 0, category: 'docs', notes: 'markdown notes' };
  }

  if (rel === 'package.json' || rel === 'package-lock.json') {
    return { required: 0, category: 'config', notes: 'npm metadata; not shipped' };
  }

  if (rel === '.gitignore') {
    return { required: 0, category: 'other-dev', notes: 'git config' };
  }

  return { required: 0, category: 'other-dev', notes: '' };
}

function auditDist() {
  if (!fs.existsSync(distDir)) {
    console.warn('[audit] dist/ missing — run npm run build first for dist ratings');
    return;
  }

  const closure = collectDistClosure();

  walkDir(distDir, 'dist', (rel) => {
    const distRel = rel.slice('dist/'.length);
    if (closure.has(distRel)) {
      addEntry(rel, 1, 'dist-runtime', 'reachable from manifest/HTML/JS closure');
    } else {
      addEntry(rel, 0, 'dist-bloat', 'in dist/ but not referenced at runtime — exclude from store zip');
    }
  });
}

function auditRepo() {
  walkDir(root, '', (rel, abs) => {
    if (rel.startsWith('dist/')) return;
    const cat = categorizeRepoFile(rel);
    if (cat) addEntry(rel, cat.required, cat.category, cat.notes);
  });
}

function csvEscape(s) {
  if (/[",\n]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
  return s;
}

function writeCsv(rows) {
  const lines = ['path,required,category,notes'];
  for (const row of rows) {
    lines.push(
      [csvEscape(row.path), row.required, csvEscape(row.category), csvEscape(row.notes)].join(','),
    );
  }
  fs.writeFileSync(path.join(docsDir, 'PACKAGE-FILE-AUDIT.csv'), `${lines.join('\n')}\n`, 'utf8');
}

function writeMd(rows) {
  const distRuntime = rows.filter((r) => r.category === 'dist-runtime');
  const distBloat = rows.filter((r) => r.category === 'dist-bloat');
  const repoRows = rows.filter((r) => !r.path.startsWith('dist/'));

  const byCategory = new Map();
  for (const r of repoRows) {
    byCategory.set(r.category, (byCategory.get(r.category) ?? 0) + 1);
  }

  const md = `# Package file audit (0/1 ship rating)

Generated by \`npm run audit:package-files\` (run after \`npm run build\` for accurate dist ratings).

## How to read

| \`required\` | Meaning |
|-------------|---------|
| **1** | Must be included in the Chrome Web Store / public extension zip |
| **0** | Dev-only or build-only — must **not** be in the public zip |

The public package is **only** the contents of \`dist/\` after \`npm run build\`. Everything else in the repo is \`required=0\`.

Full file-by-file list: [PACKAGE-FILE-AUDIT.csv](./PACKAGE-FILE-AUDIT.csv)

## Summary

| Metric | Count |
|--------|------:|
| Total paths audited | ${rows.length} |
| Dist runtime (\`required=1\`) | ${distRuntime.length} |
| Dist bloat (\`required=0\`, exclude from zip) | ${distBloat.length} |
| Repo dev-only (\`required=0\`) | ${repoRows.length} |

## Dist runtime — ship these (\`required=1\`)

| Path | Notes |
|------|-------|
${distRuntime.map((r) => `| \`${r.path}\` | ${r.notes} |`).join('\n') || '| _(none — run build first)_ | |'}

## Dist bloat — do not ship (\`required=0\`)

| Path | Notes |
|------|-------|
${distBloat.map((r) => `| \`${r.path}\` | ${r.notes} |`).join('\n') || '| _(none)_ | |'}

## Repo dev-only by category (\`required=0\`)

| Category | Files | Description |
|----------|------:|-------------|
${[...byCategory.entries()]
  .sort((a, b) => a[0].localeCompare(b[0]))
  .map(([cat, n]) => `| ${cat} | ${n} | see CSV |`)
  .join('\n')}

## Regenerate

\`\`\`bash
npm run build && npm run audit:package-files
\`\`\`
`;

  fs.writeFileSync(path.join(docsDir, 'PACKAGE-FILE-AUDIT.md'), md, 'utf8');
}

function main() {
  if (!fs.existsSync(docsDir)) fs.mkdirSync(docsDir, { recursive: true });

  auditDist();
  auditRepo();

  const rows = [...entries.entries()]
    .map(([p, v]) => ({ path: p, ...v }))
    .sort((a, b) => a.path.localeCompare(b.path));

  writeCsv(rows);
  writeMd(rows);

  const ship = rows.filter((r) => r.required === 1).length;
  const dev = rows.filter((r) => r.required === 0).length;
  console.info(`[audit:package-files] wrote ${rows.length} paths (${ship} ship, ${dev} dev-only)`);
  console.info(`  → docs/PACKAGE-FILE-AUDIT.csv`);
  console.info(`  → docs/PACKAGE-FILE-AUDIT.md`);
}

main();
